<?php

namespace App\Services;

use DateTimeImmutable;
use DateTimeZone;

class EnergySimulator
{
    public const CHARGE_EFFICIENCY = 0.95;

    public const DISCHARGE_EFFICIENCY = 0.95;

    public function initialState(?string $clock = null, bool $withHistory = true): array
    {
        $zone = new DateTimeZone('Europe/Amsterdam');
        $start = $clock ? (new DateTimeImmutable($clock))->setTimezone($zone) : (new DateTimeImmutable('now', $zone))->setTime(12, 0);
        $state = [
            'clock' => $start->format(DATE_ATOM),
            'environment' => ['weather' => 'cloudy', 'lighting' => 'day', 'unit' => 'C'],
            'controls' => ['homeMode' => 'auto', 'evMode' => 'solar', 'waterMode' => 'solar', 'exportEnabled' => false, 'gridFallback' => false],
            'configuration' => ['homeDemand' => 2.6, 'solarCapacity' => 8.0, 'batteryCapacity' => 10.0, 'batteryReserve' => 20.0,
                'batteryMaxCharge' => 3.0, 'batteryMaxDischarge' => 5.0, 'evCapacity' => 60.0, 'evChargePower' => 3.2,
                'evTarget' => 80.0, 'waterTarget' => 55.0, 'gridRate' => 0.28, 'carbonFactor' => 0.23, 'variation' => false],
            'batteryKwh' => 7.6, 'evPercent' => 68.0, 'waterTemperature' => 54.0,
            'readings' => [], 'daily' => [], 'activity' => [], 'revision' => 1, 'step' => 0,
            'schedules' => [
                ['id' => 'ev-night', 'system' => 'ev', 'source' => 'grid', 'start' => 0, 'end' => 360, 'days' => [0, 1, 2, 3, 4, 5, 6], 'enabled' => true],
                ['id' => 'ev-solar', 'system' => 'ev', 'source' => 'solar', 'start' => 660, 'end' => 960, 'days' => [0, 1, 2, 3, 4, 5, 6], 'enabled' => true],
                ['id' => 'water-solar', 'system' => 'water', 'source' => 'solar', 'start' => 480, 'end' => 960, 'days' => [0, 1, 2, 3, 4, 5, 6], 'enabled' => true],
                ['id' => 'water-evening', 'system' => 'water', 'source' => 'grid', 'start' => 1080, 'end' => 1200, 'days' => [0, 1, 2, 3, 4, 5, 6], 'enabled' => true],
            ],
        ];
        if ($withHistory) {
            $state['clock'] = $start->modify('-7 days')->format(DATE_ATOM);
            $state['controls']['gridFallback'] = true;
            $state['controls']['evMode'] = 'schedule';
            $state['controls']['waterMode'] = 'schedule';
            $state['configuration']['variation'] = true;
            while ((new DateTimeImmutable($state['clock']))->getTimestamp() < $start->getTimestamp()) {
                $at = $this->clock($state);
                $hour = (int) $at->format('G') + ((int) $at->format('i')) / 60;
                $state['environment']['lighting'] = $hour >= 7 && $hour < 19 ? 'day' : 'night';
                $state['environment']['weather'] = ((int) $at->format('z') % 4 === 0) ? 'cloudy' : 'sunny';
                $state['configuration']['solarCapacity'] = 8.0 * max(0, sin(M_PI * ($hour - 7) / 12));
                $state = $this->step($state, min(600, $start->getTimestamp() - $at->getTimestamp()));
                if ($at->format('H:i') === '18:00') {
                    $state['evPercent'] = max(20, $state['evPercent'] - 22);
                }
            }
            $state['clock'] = $start->format(DATE_ATOM);
            $state['environment'] = ['weather' => 'cloudy', 'lighting' => 'day', 'unit' => 'C'];
            $state['configuration']['solarCapacity'] = 8.0;
            $state['configuration']['variation'] = false;
            $state['controls'] = ['homeMode' => 'auto', 'evMode' => 'solar', 'waterMode' => 'solar', 'exportEnabled' => false, 'gridFallback' => false];
            $state['batteryKwh'] = 7.6;
            $state['evPercent'] = 68.0;
            $state['waterTemperature'] = 54.0;
        }

        return $this->log($state, 'Demo ready', 'Seven-day sample history generated by the same simulation engine. Current conditions: cloudy daytime.', 'system');
    }

    public function effectiveMode(array $state, string $system): string
    {
        $mode = $state['controls'][$system.'Mode'];
        if ($mode !== 'schedule') {
            return $mode;
        }
        $at = $this->clock($state);
        $minute = (int) $at->format('G') * 60 + (int) $at->format('i');
        $day = (int) $at->format('N') - 1;
        foreach ($state['schedules'] as $block) {
            if ($block['enabled'] && $block['system'] === $system && in_array($day, $block['days'], true) && $minute >= $block['start'] && $minute < $block['end']) {
                return $block['source'];
            }
        }

        return 'off';
    }

    public function power(array $state, float $hours = 1 / 60): array
    {
        $c = $state['configuration'];
        $minute = intdiv((new DateTimeImmutable($state['clock']))->getTimestamp(), 60);
        $variation = $c['variation'] ? 1 + (sin($minute * 0.71) * 0.08) : 1;
        $weatherFactor = ['sunny' => 1.0, 'cloudy' => 0.15, 'rainy' => 0.05][$state['environment']['weather']];
        $sun = $state['environment']['lighting'] === 'day' ? $weatherFactor : 0;
        $available = $c['solarCapacity'] * $sun * $variation;
        $remaining = $available;
        $home = $state['controls']['homeMode'] === 'off' ? 0 : $c['homeDemand'] * $variation;
        $solarHome = $gridHome = $discharge = $unmet = 0.0;
        if ($state['controls']['homeMode'] === 'grid') {
            $gridHome = $home;
        } elseif ($state['controls']['homeMode'] === 'auto') {
            $solarHome = min($remaining, $home);
            $remaining -= $solarHome;
            $reserve = $c['batteryCapacity'] * $c['batteryReserve'] / 100;
            $usable = max(0, $state['batteryKwh'] - $reserve);
            $discharge = min(max(0, $home - $solarHome), $c['batteryMaxDischarge'], $usable * self::DISCHARGE_EFFICIENCY / $hours);
            $unmet = max(0, $home - $solarHome - $discharge);
            if ($state['controls']['gridFallback']) {
                $gridHome = $unmet;
                $unmet = 0.0;
            }
        }

        $evMode = $this->effectiveMode($state, 'ev');
        $evRoom = max(0, ($c['evTarget'] - $state['evPercent']) / 100 * $c['evCapacity']);
        $evLimit = min($c['evChargePower'], $evRoom / ($hours * 0.92));
        $solarEv = $evMode === 'solar' ? min($remaining, $evLimit) : 0.0;
        if ($solarEv < min(1.4, $evLimit)) {
            $solarEv = 0.0;
        }
        $remaining -= $solarEv;
        $gridEv = $evMode === 'grid' ? $evLimit : 0.0;
        $evPower = $solarEv + $gridEv;
        $evStatus = $state['evPercent'] >= $c['evTarget'] - 0.001 ? 'Charge limit reached' : ($evPower > 0.001 ? 'Charging' : ($evMode === 'solar' ? 'Paused · low solar' : 'Off'));

        $waterMode = $this->effectiveMode($state, 'water');
        $thermal = min(2.5 * $sun, max(0, (85 - $state['waterTemperature']) * 0.2326 / $hours));
        $heatLoss = max(0, ($state['waterTemperature'] - 20) * 0.002) + 0.12;
        $waterPower = $waterMode === 'grid' ? min(2.0, max(0, ($c['waterTarget'] - $state['waterTemperature']) * 0.2326 / $hours + $heatLoss - $thermal)) : 0.0;

        $room = max(0, $c['batteryCapacity'] - $state['batteryKwh']);
        $charge = $discharge > 0.000001 ? 0.0 : min($remaining, $c['batteryMaxCharge'], $room / ($hours * self::CHARGE_EFFICIENCY));
        $remaining -= $charge;
        $export = $state['controls']['exportEnabled'] ? $remaining : 0.0;
        $curtailed = $remaining - $export;
        $status = $discharge > 0.001 ? 'Discharging' : ($charge > 0.001 ? 'Charging' : 'Idle');
        $reason = $discharge > 0.001 ? ($state['environment']['lighting'] === 'night' ? 'Nighttime home backup' : 'Covering the home solar shortfall') :
            ($charge > 0.001 ? 'Storing surplus rooftop solar' : ($state['batteryKwh'] <= $c['batteryCapacity'] * $c['batteryReserve'] / 100 + 0.001 ? 'Minimum reserve protected' : 'Home demand covered'));

        return [
            'solarAvailable' => $available, 'solarGenerated' => $available - $curtailed,
            'solarHome' => $solarHome, 'solarEv' => $solarEv, 'homeDemand' => $home, 'homeSupplied' => $home - $unmet,
            'evPower' => $evPower, 'waterPower' => $waterPower, 'thermalPower' => $thermal,
            'gridImport' => $gridHome + $gridEv + $waterPower, 'gridExport' => $export,
            'batteryCharge' => $charge, 'batteryDischarge' => $discharge,
            'curtailed' => $curtailed, 'unmetHome' => $unmet, 'gridHome' => $gridHome, 'gridEv' => $gridEv,
            'batteryPercent' => $state['batteryKwh'] / $c['batteryCapacity'] * 100,
            'batteryStatus' => $status, 'batteryReason' => $reason, 'evStatus' => $evStatus,
            'effectiveEvMode' => $evMode, 'effectiveWaterMode' => $waterMode,
        ];
    }

    public function advance(array $state, int $seconds): array
    {
        while ($seconds > 0) {
            $secondsToBoundary = 60 - (int) (new DateTimeImmutable($state['clock']))->format('s');
            $step = min($secondsToBoundary, $seconds);
            $state = $this->step($state, $step);
            $seconds -= $step;
        }
        $state['revision']++;

        return $state;
    }

    private function step(array $state, int $seconds): array
    {
        $hours = $seconds / 3600;
        $p = $this->power($state, $hours);
        $date = substr($state['clock'], 0, 10);
        $c = $state['configuration'];
        $state['batteryKwh'] = min($c['batteryCapacity'], max(0, $state['batteryKwh'] + ($p['batteryCharge'] * self::CHARGE_EFFICIENCY - $p['batteryDischarge'] / self::DISCHARGE_EFFICIENCY) * $hours));
        $state['evPercent'] = min(100, $state['evPercent'] + $p['evPower'] * $hours * 0.92 / $c['evCapacity'] * 100);
        $loss = max(0, ($state['waterTemperature'] - 20) * 0.002) + 0.12;
        $state['waterTemperature'] = max(20, min(85, $state['waterTemperature'] + ($p['thermalPower'] + $p['waterPower'] - $loss) * $hours / 0.2326));
        $storageLoss = $p['batteryCharge'] * (1 - self::CHARGE_EFFICIENCY) + $p['batteryDischarge'] * (1 / self::DISCHARGE_EFFICIENCY - 1);
        $values = ['solar' => $p['solarGenerated'], 'grid' => $p['gridImport'], 'exported' => $p['gridExport'],
            'home' => $p['homeSupplied'], 'ev' => $p['evPower'], 'water' => $p['waterPower'], 'thermal' => $p['thermalPower'],
            'batteryCharged' => $p['batteryCharge'], 'batteryDischarged' => $p['batteryDischarge'], 'batteryLosses' => $storageLoss,
            'curtailed' => $p['curtailed'], 'unmet' => $p['unmetHome'],
            'savings' => ($p['solarHome'] + $p['solarEv'] + $p['batteryDischarge']) * $c['gridRate'],
            'carbon' => ($p['solarHome'] + $p['solarEv'] + $p['batteryDischarge']) * $c['carbonFactor']];
        if (! isset($state['daily'][$date])) {
            $state['daily'][$date] = ['date' => $date] + array_fill_keys(array_keys($values), 0.0);
        }
        foreach ($values as $key => $value) {
            $state['daily'][$date][$key] += $value * $hours;
        }
        $previousEv = $p['effectiveEvMode'];
        $previousWater = $p['effectiveWaterMode'];
        $at = $this->clock($state)->setTimestamp($this->clock($state)->getTimestamp() + $seconds);
        $state['clock'] = $at->format(DATE_ATOM);
        $state['step']++;
        if (($at->format('i') % 10 === 0 && $at->format('s') === '00') || count($state['readings']) === 0) {
            $state['readings'][] = $this->reading($state);
            $state['readings'] = array_slice($state['readings'], -1152);
        }
        $state['daily'] = array_slice($state['daily'], -31, null, true);
        foreach (['ev' => $previousEv, 'water' => $previousWater] as $system => $before) {
            $after = $this->effectiveMode($state, $system);
            if ($before !== $after) {
                $state = $this->log($state, ucfirst($system).' schedule switched to '.$after, 'Automatic rule at '.$at->format('H:i'), 'schedule');
            }
        }

        return $state;
    }

    public function reading(array $state): array
    {
        $p = $this->power($state);

        return ['time' => $state['clock'], 'solar' => $p['solarGenerated'], 'home' => $p['homeSupplied'], 'grid' => $p['gridImport'],
            'batteryCharge' => $p['batteryCharge'], 'batteryDischarge' => $p['batteryDischarge'], 'ev' => $p['evPower'],
            'waterTemperature' => $state['waterTemperature'], 'batteryPercent' => $p['batteryPercent'], 'exported' => $p['gridExport']];
    }

    private function clock(array $state): DateTimeImmutable
    {
        return (new DateTimeImmutable($state['clock']))->setTimezone(new DateTimeZone('Europe/Amsterdam'));
    }

    public function log(array $state, string $title, string $detail, string $kind = 'control'): array
    {
        array_unshift($state['activity'], ['id' => bin2hex(random_bytes(6)), 'time' => $state['clock'], 'title' => $title, 'detail' => $detail, 'kind' => $kind]);
        $state['activity'] = array_slice($state['activity'], 0, 50);

        return $state;
    }

    public function snapshot(array $state): array
    {
        $readings = $state['readings'];
        $readings[] = $this->reading($state);

        return [
            'clock' => $state['clock'], 'environment' => $state['environment'], 'controls' => $state['controls'],
            'configuration' => $state['configuration'], 'batteryKwh' => $state['batteryKwh'],
            'evPercent' => $state['evPercent'], 'waterTemperature' => $state['waterTemperature'],
            'telemetry' => $this->power($state), 'readings' => $readings,
            'daily' => array_values($state['daily']), 'activity' => $state['activity'],
            'schedules' => $state['schedules'], 'revision' => $state['revision'], 'transport' => 'gRPC · Protocol Buffers',
        ];
    }
}
