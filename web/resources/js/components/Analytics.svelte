<script lang="ts">
    import Icon from "./Icon.svelte";
    import PowerChart from "./PowerChart.svelte";
    import DeviceArt from "./DeviceArt.svelte";
    import Sparkline from "./Sparkline.svelte";
    import { number, money, dayName, temperature } from "../lib/format";
    import type { Snapshot } from "../generated/energy_pb";
    let { simulation }: { simulation: Snapshot } = $props();
    let range = $state(7),
        historyKind = $state<"battery" | "water">("battery");
    const today = $derived(simulation.clock.slice(0, 10));
    const firstDate = $derived(
        new Date(
            new Date(today + "T12:00:00Z").getTime() - (range - 1) * 86400000,
        )
            .toISOString()
            .slice(0, 10),
    );
    const rows = $derived(
        simulation.daily.filter((d) => d.date >= firstDate && d.date <= today),
    );
    const sum = (key: string) =>
        rows.reduce((a, d) => a + Number(d[key as keyof typeof d]), 0);
    const solar = $derived(sum("solar")),
        grid = $derived(sum("grid")),
        home = $derived(sum("home")),
        ev = $derived(sum("ev")),
        water = $derived(sum("water")),
        used = $derived(home + ev + water);
    const maxBar = $derived(Math.max(1, ...rows.map((d) => d.solar + d.grid)));
    const cumulative = $derived.by(() => {
        let total = 0;
        return rows.map((d) => ({ date: d.date, value: (total += d.solar) }));
    });
    const cumPath = $derived(
        cumulative
            .map(
                (d, i) =>
                    (i ? "L" : "M") +
                    (cumulative.length === 1
                        ? 317
                        : 35 + (i / (cumulative.length - 1)) * 565) +
                    "," +
                    (165 - (d.value / Math.max(1, solar)) * 135),
            )
            .join(" "),
    );
    function download() {
        const csv = [
            "Date,PV electricity kWh,Grid import kWh,Home kWh,EV kWh,Water backup kWh,Solar heat kWhth,Export kWh,Battery charged kWh,Battery discharged kWh,Storage losses kWh,Estimated savings EUR,Estimated CO2 avoided kg",
            ...rows.map((d) =>
                [
                    d.date,
                    d.solar,
                    d.grid,
                    d.home,
                    d.ev,
                    d.water,
                    d.thermal,
                    d.exported,
                    d.batteryCharged,
                    d.batteryDischarged,
                    d.batteryLosses,
                    d.savings,
                    d.carbon,
                ]
                    .map((v) => (typeof v === "number" ? v.toFixed(4) : v))
                    .join(","),
            ),
        ].join("\r\n");
        const a = document.createElement("a");
        a.href = URL.createObjectURL(
            new Blob([csv], { type: "text/csv;charset=utf-8" }),
        );
        a.download = "ThermaVoltFlow-energy-report.csv";
        a.click();
        URL.revokeObjectURL(a.href);
    }
</script>

<div class="page-toolbar">
    <div>
        <span class="pill"
            ><Icon name="activity" size={14} />From saved simulation readings</span
        >
        <p class="muted">Electricity and solar heat are measured separately.</p>
    </div>
    <div class="button-row">
        <select
            class="compact-select"
            aria-label="Analytics period"
            bind:value={range}
            ><option value={1}>Today</option><option value={7}
                >Last 7 days</option
            ><option value={30}>Last 30 days</option></select
        ><button class="secondary" onclick={download}
            ><Icon name="download" size={16} />Export CSV</button
        >
    </div>
</div>
<div class="analytics-kpis">
    {#each [{ icon: "sun", title: "PV electricity", value: number(solar), unit: "kWh", note: "Generated by your rooftop", tone: "green", data: rows.map((d) => d.solar), color: "#00ef7d" }, { icon: "home", title: "Electricity used", value: number(used), unit: "kWh", note: "Home, EV & water backup", tone: "blue", data: rows.map((d) => d.home + d.ev + d.water), color: "#439df5" }, { icon: "import", title: "Grid import", value: number(grid), unit: "kWh", note: "Purchased electricity", tone: "amber", data: rows.map((d) => d.grid), color: "#ffad23" }, { icon: "leaf", title: "Estimated savings", value: money(sum("savings")), unit: "", note: "Configured tariff estimate", tone: "green", data: rows.map((d) => d.savings), color: "#00ef7d" }, { icon: "leaf", title: "CO₂ avoided", value: number(sum("carbon")), unit: "kg", note: "Configured factor estimate", tone: "green", data: rows.map((d) => d.carbon), color: "#00ef7d" }] as item}
        <div class="panel analytics-kpi">
            <div class="metric-caption">
                <span class={item.tone}
                    ><Icon name={item.icon} size={19} /></span
                >{item.title}
            </div>
            <strong>{item.value}<small>{item.unit}</small></strong>
            <Sparkline values={item.data} color={item.color} /><span
                class="muted tiny">{item.note}</span
            >
        </div>
    {/each}
</div>
<div class="analytics-main">
    <section class="panel">
        <div class="panel-heading">
            <div>
                <h3>Daily electricity mix</h3>
                <p class="muted tiny">PV generation and utility import</p>
            </div>
            <span class="pill">kWh</span>
        </div>
        <div class="chart-legend">
            <span><i class="solar-dot"></i>PV electricity</span><span
                ><i class="grid-dot"></i>Grid import</span
            >
        </div>
        <div class="bar-chart">
            <div class="bar-grid">
                {#each [0, 1, 2, 3] as n}<span
                        style:bottom={(n / 3) * 100 + "%"}
                        >{number((maxBar * n) / 3, 0)}</span
                    >{/each}
            </div>
            {#each rows as d}<div
                    class="bar-column"
                    title={d.date +
                        ": PV " +
                        number(d.solar) +
                        " kWh, grid " +
                        number(d.grid) +
                        " kWh"}
                >
                    <span class="bar-total">{number(d.solar + d.grid, 1)}</span>
                    <div
                        class="bar-stack"
                        style:height={((d.solar + d.grid) / maxBar) * 196 +
                            "px"}
                    >
                        <div
                            class="bar-grid-part"
                            style:height={(d.grid /
                                Math.max(0.01, d.solar + d.grid)) *
                                100 +
                                "%"}
                        ></div>
                        <div
                            class="bar-solar-part"
                            style:height={(d.solar /
                                Math.max(0.01, d.solar + d.grid)) *
                                100 +
                                "%"}
                        ></div>
                    </div>
                    <span class="bar-day">{dayName(d.date)}</span>
                </div>{/each}
        </div>
    </section>
    <section class="panel">
        <div class="panel-heading">
            <h3>Electricity by system</h3>
            <Icon name="home" size={18} />
        </div>
        <div class="donut-row">
            <div
                class="donut"
                style:background={"conic-gradient(#439df5 0 " +
                    (home / Math.max(0.001, used)) * 100 +
                    "%,#23ec75 " +
                    (home / Math.max(0.001, used)) * 100 +
                    "% " +
                    ((home + ev) / Math.max(0.001, used)) * 100 +
                    "%,#ffad23 0)"}
            >
                <div><strong>{number(used)}</strong><span>kWh used</span></div>
            </div>
            <div class="donut-legend">
                {#each [{ name: "Home", value: home, color: "#439df5", icon: "home" }, { name: "EV charging", value: ev, color: "#23ec75", icon: "ev" }, { name: "Water backup", value: water, color: "#ffad23", icon: "water" }] as item}<div
                    >
                        <span style:color={item.color}
                            ><Icon name={item.icon} size={19} /></span
                        ><span>{item.name}<b>{number(item.value)} kWh</b></span
                        ><small
                            >{number(
                                (item.value / Math.max(0.001, used)) * 100,
                                0,
                            )}%</small
                        >
                    </div>{/each}
            </div>
        </div>
        <p class="tiny muted">
            Solar thermal heat is excluded from electricity use.
        </p>
    </section>
</div>
<div class="analytics-secondary">
    <section class="panel cumulative">
        <div class="panel-heading">
            <h3>Cumulative PV yield</h3>
            <span class="pill">kWh</span>
        </div>
        <svg
            viewBox="0 0 630 200"
            role="img"
            aria-label="Cumulative PV electricity chart"
            >{#each [0, 1, 2, 3] as i}<line
                    x1="35"
                    x2="600"
                    y1={165 - i * 45}
                    y2={165 - i * 45}
                    stroke="#233139"
                    stroke-dasharray="3 5"
                /><text x="28" y={169 - i * 45} text-anchor="end"
                    >{number((solar * i) / 3, 0)}</text
                >{/each}{#if cumulative.length > 1}<path
                    d={cumPath + " L600 165 L35 165 Z"}
                    fill="#00ef7d"
                    fill-opacity=".22"
                /><path
                    d={cumPath}
                    stroke="#00ef7d"
                    stroke-width="2"
                    fill="none"
                />{/if}{#each cumulative as d, i}<circle
                    cx={cumulative.length === 1
                        ? 317
                        : 35 + (i / (cumulative.length - 1)) * 565}
                    cy={165 - (d.value / Math.max(1, solar)) * 135}
                    r="3"
                    fill="#00ef7d"
                /><text
                    x={cumulative.length === 1
                        ? 317
                        : 35 + (i / (cumulative.length - 1)) * 565}
                    y="191"
                    text-anchor="middle">{dayName(d.date)}</text
                >{/each}</svg
        >
    </section>
    <section class="panel thermal-stat">
        <div class="panel-heading">
            <h3>Solar thermal</h3>
            <span class="amber"><Icon name="water" size={20} /></span>
        </div>
        <DeviceArt device="water" class="thermal-art" />
        <strong>{number(sum("thermal"))}<small>kWhth</small></strong>
        <p class="muted">
            Heat collected<span class="thermal-temp"
                >{temperature(
                    simulation.waterTemperature,
                    simulation.environment!.unit,
                )}</span
            ><small>Current water temperature</small>
        </p>
    </section>
    <section class="panel export-stat">
        <div class="panel-heading">
            <h3>Grid export</h3>
            <span class="pill"
                >{simulation.controls?.exportEnabled
                    ? "Enabled"
                    : "Disabled"}</span
            >
        </div>
        <Icon name="export" size={32} /><strong
            >{number(sum("exported"))}<small>kWh</small></strong
        >
        <p class="muted">Surplus PV electricity only</p>
        <small class="muted"
            >{sum("exported") > 0.001
                ? "Export events are included in the report."
                : "No export events in this period."}</small
        >
    </section>
</div>
<section class="panel">
    <div class="panel-heading">
        <div>
            <h3>Storage & temperature history</h3>
            <p class="muted tiny">Last 24 simulated hours</p>
        </div>
        <div class="segmented">
            <button
                class:active={historyKind === "battery"}
                onclick={() => (historyKind = "battery")}>Battery</button
            ><button
                class:active={historyKind === "water"}
                onclick={() => (historyKind = "water")}>Water</button
            >
        </div>
    </div>
    <PowerChart
        readings={simulation.readings}
        kind={historyKind}
        unit={simulation.environment?.unit}
    />
    <div class="storage-totals">
        <span>Charged <b>{number(sum("batteryCharged"))} kWh</b></span><span
            >Delivered to home <b>{number(sum("batteryDischarged"))} kWh</b
            ></span
        ><span>Storage losses <b>{number(sum("batteryLosses"))} kWh</b></span>
    </div>
</section>
<section class="panel export-history">
    <div class="panel-heading">
        <div>
            <h3>Export history</h3>
            <p class="tiny muted">
                Daily totals from the selected reporting period
            </p>
        </div>
        <Icon name="export" size={19} />
    </div>
    {#if rows.some((d) => d.exported > 0.0001)}<table>
            <thead
                ><tr><th>Date</th><th>Sent to utility</th><th>Source</th></tr
                ></thead
            ><tbody
                >{#each [...rows]
                    .reverse()
                    .filter((d) => d.exported > 0.0001) as d}<tr
                        ><td>{d.date}</td><td class="green"
                            >{number(d.exported, 2)} kWh</td
                        ><td>Surplus rooftop PV</td></tr
                    >{/each}</tbody
            >
        </table>{:else}<div class="empty-history">
            <Icon name="export" size={24} /><span
                >No electricity exported in this period.<small
                    >Enable Export surplus, choose sunny daytime, and advance
                    the simulation after the loads and battery are supplied.</small
                ></span
            >
        </div>{/if}
</section>
